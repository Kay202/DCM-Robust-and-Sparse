fmt <- function(x, digits = 3) {
  ifelse(is.finite(x), formatC(x, digits = digits, format = "f"), "--")
}
pm <- function(mean, se, digits = 3) paste0(fmt(mean, digits), " (", fmt(se, digits), ")")
append_tex <- function(x) cat(paste0(x, collapse = "\n"), "\n", file = "simulation_tables_generated.tex", append = TRUE)
begin_table <- function(caption, label, columns, header, size = "\\small", resize = FALSE) {
  out <- c(
    "\\begin{table}[htbp]", "\\centering", size, "\\setlength{\\tabcolsep}{4pt}",
    paste0("\\caption{", caption, "}"), paste0("\\label{", label, "}")
  )
  if (resize) out <- c(out, "\\resizebox{\\textwidth}{!}{%")
  out <- c(out, paste0("\\begin{tabular}{", columns, "}"), "\\toprule", paste0(header, "\\\\"), "\\midrule")
  append_tex(out)
}
end_table <- function(resize = FALSE) {
  out <- c("\\bottomrule", "\\end{tabular}")
  if (resize) out <- c(out, "}")
  append_tex(c(out, "\\end{table}", ""))
}
row_tex <- function(x) append_tex(paste0(paste(x, collapse = " & "), "\\\\"))

