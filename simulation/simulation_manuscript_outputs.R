# Main Figure 1: contamination fraction and magnitude.
draw_series <- function(data, x, metric, xlab, ylab, panel) {
  yr <- range(data[[metric]], finite = TRUE)
  pad <- 0.06 * diff(yr)
  plot(range(x), yr + c(-pad, pad), type = "n", xlab = xlab, ylab = ylab, main = panel, las = 1)
  grid(col = "#E6E6E6")
  for (a in arm_order) {
    z <- data[data$arm == a, ]
    ord <- order(x[data$arm == a])
    lines(x[data$arm == a][ord], z[[metric]][ord], col = plot_col[a], pch = plot_pch[a], lty = plot_lty[a], lwd = 2, type = "o")
  }
}
